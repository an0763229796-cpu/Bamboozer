type TranslationMap = {
  vi: Record<string, string>;
  en: Record<string, string>;
  zh: Record<string, string>;
};

const typedTranslations = translations as TranslationMap;

type TranslationKey = keyof typeof typedTranslations.vi;
type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey) => string;
  tContent: (key: string, fallback?: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem('bamboozer-language');
    if (saved === 'vi' || saved === 'en' || saved === 'zh') return saved;
    return 'zh';
  });

  const setLanguage = (nextLanguage: Language) => {
    setLanguageState(nextLanguage);
    localStorage.setItem('bamboozer-language', nextLanguage);
    document.documentElement.lang = nextLanguage === 'zh' ? 'zh-CN' : nextLanguage;
  };

  useEffect(() => {
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : language;
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t: (key: TranslationKey) => typedTranslations[language][key],
      tContent: (key: string, fallback = key) => contentTranslations[key]?.[language] || fallback,
    }),
    [language],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider');
  return context;
}
