// Helper to generate realistic sample trade history
function generateTrades(traderId: string, count: number, winRate: number): TradeHistory[] {
  const symbols = ['BTC/USDT', 'ETH/USDT', 'SOL/USDT', 'BNB/USDT'];
  const trades: TradeHistory[] = [];
  const basePrices: Record<string, number> = {
    'BTC/USDT': 91200,
    'ETH/USDT': 3380,
    'SOL/USDT': 188,
    'BNB/USDT': 640,
  };

  for (let i = 1; i <= count; i++) {
    const sym = symbols[i % symbols.length];
    const isWin = Math.random() * 100 < winRate;
    const side: 'LONG' | 'SHORT' = i % 2 === 0 ? 'LONG' : 'SHORT';
    const lev = Math.min(20, Math.floor(Math.random() * 12) + 5);
    const baseP = basePrices[sym];
    const pnlPercent = isWin
      ? +(Math.random() * 18 + 4).toFixed(2)
      : -(Math.random() * 7 + 1).toFixed(2);
    const pnl = +(pnlPercent * lev * 2.5).toFixed(2);

    trades.push({
      id: `trd-${traderId}-${i}`,
      participantId: traderId,
      symbol: sym,
      side,
      leverage: lev,
      entryPrice: +(baseP * (1 + (Math.random() - 0.5) * 0.02)).toFixed(2),
      closePrice: +(baseP * (1 + (isWin ? 0.015 : -0.01))).toFixed(2),
      pnl,
      pnlPercent,
      openedAt: `2026-09-${(20 + Math.floor(i / 3)).toString().padStart(2, '0')} 09:30:00`,
      closedAt: `2026-09-${(20 + Math.floor(i / 3)).toString().padStart(2, '0')} 14:45:00`,
      status: 'CLOSED',
    });
  }

  return trades;
}

